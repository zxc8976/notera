// 獲取翻譯文字的函數
export function getTranslation(key, language = 'zh-TW') {
  const messages = i18nMessages[language] || i18nMessages['zh-TW']
  return messages[key] || key
}

// 創建響應式翻譯函數
export function createI18n(currentLanguage) {
  const setLocale = (newLocale) => {
    if (currentLanguage && currentLanguage.value !== undefined) {
      currentLanguage.value = newLocale
    }
  }

  return {
    // t 函數支援參數替換，如 t('totalVideosCount', { count: 3 })
    t: (key, vars) => {
      const message = getTranslation(key, currentLanguage?.value || 'zh-TW')
      if (!vars) return message
      return message.replace(/\{(\w+)\}/g, (_, k) =>
        Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : `{${k}}`
      )
    },
    setLocale,
    locale: currentLanguage
  }
}
